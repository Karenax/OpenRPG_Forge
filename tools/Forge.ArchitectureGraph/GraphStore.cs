using System.Security.Cryptography;
using System.Text;
using System.Text.Json;

namespace Forge.ArchitectureGraph;

public static class GraphStore
{
    public static readonly JsonSerializerOptions JsonOptions = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.SnakeCaseLower,
        DictionaryKeyPolicy = null,
        WriteIndented = true,
    };

    public static byte[] Serialize(GraphDocument graph)
    {
        var json = JsonSerializer.Serialize(graph, JsonOptions)
            .Replace("\r\n", "\n", StringComparison.Ordinal);
        return Encoding.UTF8.GetBytes(json + "\n");
    }

    public static GraphDocument Load(string path)
    {
        using var stream = File.OpenRead(path);
        return JsonSerializer.Deserialize<GraphDocument>(stream, JsonOptions)
            ?? throw new InvalidDataException($"Architecture graph is empty: {path}");
    }

    public static byte[] BuildOverview(GraphDocument graph)
    {
        var nodeById = graph.Nodes.ToDictionary(node => node.Id, StringComparer.Ordinal);
        var kindCounts = graph.Nodes
            .GroupBy(node => node.Kind, StringComparer.Ordinal)
            .ToDictionary(group => group.Key, group => group.Count(), StringComparer.Ordinal);
        var selectedKinds = kindCounts
            .OrderByDescending(pair => pair.Value)
            .ThenBy(pair => pair.Key, StringComparer.Ordinal)
            .Take(18)
            .Select(pair => pair.Key)
            .ToHashSet(StringComparer.Ordinal);
        var edgeCounts = graph.Edges
            .Where(edge => nodeById.ContainsKey(edge.Source) && nodeById.ContainsKey(edge.Target))
            .Select(edge => new
            {
                SourceKind = nodeById[edge.Source].Kind,
                TargetKind = nodeById[edge.Target].Kind,
                edge.Kind,
            })
            .Where(edge => selectedKinds.Contains(edge.SourceKind) && selectedKinds.Contains(edge.TargetKind))
            .GroupBy(
                edge => (edge.SourceKind, edge.TargetKind, edge.Kind),
                EqualityComparer<(string SourceKind, string TargetKind, string Kind)>.Default)
            .Select(group => (group.Key.SourceKind, group.Key.TargetKind, group.Key.Kind, Count: group.Count()))
            .OrderByDescending(item => item.Count)
            .ThenBy(item => item.SourceKind, StringComparer.Ordinal)
            .ThenBy(item => item.TargetKind, StringComparer.Ordinal)
            .ThenBy(item => item.Kind, StringComparer.Ordinal)
            .Take(50)
            .ToArray();

        var lines = new List<string>
        {
            "%% Generated by Forge.ArchitectureGraph (Roslyn). Do not edit.",
            "flowchart LR",
        };
        foreach (var kind in selectedKinds.Order(StringComparer.Ordinal))
        {
            lines.Add($"  {MermaidId(kind)}[\"{EscapeMermaid(kind)} ({kindCounts[kind]})\"]");
        }

        foreach (var edge in edgeCounts)
        {
            lines.Add(
                $"  {MermaidId(edge.SourceKind)} -->|\"{EscapeMermaid(edge.Kind)} ({edge.Count})\"| "
                + MermaidId(edge.TargetKind));
        }

        if (selectedKinds.Count == 0)
        {
            lines.Add("  empty[\"No analyzable nodes\"]");
        }

        return Encoding.UTF8.GetBytes(string.Join('\n', lines) + "\n");
    }

    public static void WriteAtomically(params (string Path, byte[] Content)[] artifacts)
    {
        var staged = new List<(string TemporaryPath, string Destination)>();
        try
        {
            foreach (var artifact in artifacts)
            {
                var destination = Path.GetFullPath(artifact.Path);
                var directory = Path.GetDirectoryName(destination)
                    ?? throw new InvalidOperationException($"No output directory for {destination}");
                Directory.CreateDirectory(directory);
                var temporaryPath = Path.Combine(
                    directory,
                    $".{Path.GetFileName(destination)}.{Guid.NewGuid():N}.tmp");
                using (var stream = new FileStream(
                           temporaryPath,
                           FileMode.CreateNew,
                           FileAccess.Write,
                           FileShare.None,
                           64 * 1024,
                           FileOptions.WriteThrough))
                {
                    stream.Write(artifact.Content);
                    stream.Flush(flushToDisk: true);
                }

                staged.Add((temporaryPath, destination));
            }

            foreach (var (temporaryPath, destination) in staged)
            {
                File.Move(temporaryPath, destination, overwrite: true);
            }
        }
        finally
        {
            foreach (var (temporaryPath, _) in staged)
            {
                if (File.Exists(temporaryPath))
                {
                    File.Delete(temporaryPath);
                }
            }
        }
    }

    public static string MermaidId(string value) =>
        $"n_{Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(value)))[..12]}";

    public static string EscapeMermaid(string value) =>
        value.Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("\"", "&quot;", StringComparison.Ordinal);
}
