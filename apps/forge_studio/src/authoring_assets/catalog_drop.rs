//! Studio-owned mouse gesture; no native transfer or external file authority.
use super::placement_controls::{head, insertion};
use forge_assets::asset_browser::AssetBrowser;
use forge_core::Transform;
use forge_project::authoring::{AuthoringRequest, AuthoringState};
use forge_world::placement_snap::PlacementSnap;
use leptos::prelude::*;
use std::cell::{Cell, RefCell};
use wasm_bindgen::JsCast;

type Picked = Callback<Result<Vec<[f32; 2]>, String>>;
struct Gesture {
    start: [i32; 2],
    moved: bool,
    callback: Picked,
}
thread_local! {
    static PENDING: RefCell<Option<Gesture>> = const { RefCell::new(None) };
    static SUPPRESS_CLICK: Cell<bool> = const { Cell::new(false) };
}

pub(crate) fn cancel() {
    PENDING.with(|slot| slot.replace(None));
    SUPPRESS_CLICK.with(|slot| slot.set(false));
}

pub(super) fn consume_click(event: &web_sys::MouseEvent) -> bool {
    // A keyboard activation has no preceding mousedown to clear a completed drag.
    // Only suppress the mouse click generated by that drag, never Enter/Space.
    let suppress = SUPPRESS_CLICK.with(|slot| slot.replace(false));
    suppress && event.detail() != 0
}

pub(super) fn begin(
    event: &web_sys::MouseEvent,
    state: RwSignal<Option<AuthoringState>>,
    catalog: RwSignal<Option<AssetBrowser>>,
    selected: RwSignal<String>,
    busy: RwSignal<bool>,
    name: String,
    on_command: Callback<Result<AuthoringRequest, String>>,
) {
    if event.button() != 0 {
        return;
    }
    super::cancel_preview();
    let setup = (|| {
        if busy.get_untracked() || !crate::authoring_viewport::can_preview_asset() {
            return Err("Attendre la zone en mode édition avant de glisser un asset".into());
        }
        let source = head(state.get_untracked())?;
        let browser = super::catalog::resolve(catalog.get_untracked().as_ref(), &name)?;
        let reference = browser.reference();
        Ok::<_, String>((source.content_hash()?, browser, reference))
    })();
    let (expected, browser, reference) = match setup {
        Ok(value) => value,
        Err(error) => {
            event.prevent_default();
            on_command.run(Err(error));
            return;
        }
    };
    selected.set(name.clone());
    let ticket = super::preview::ticket();
    let callback = Callback::new(move |points: Result<Vec<[f32; 2]>, String>| {
        let point = match points.and_then(|points| {
            points
                .first()
                .copied()
                .ok_or("Déposer sur le terrain".into())
        }) {
            Ok(point) => point,
            Err(error) => {
                on_command.run(Err(error));
                return;
            }
        };
        busy.set(true);
        super::placements::report("Dépôt reçu : contrôle des ressources avant aperçu…");
        let browser = browser.clone();
        let name = name.clone();
        wasm_bindgen_futures::spawn_local(async move {
            let checked = browser.check().await;
            busy.set(false);
            if !super::preview::is_current(ticket) || selected.get_untracked() != name {
                return;
            }
            let result = checked.and_then(|_| {
                browser.still_available()?;
                let current = head(state.get_untracked())?;
                if current.content_hash()? != expected
                    || !crate::authoring_viewport::can_preview_asset()
                {
                    return Err("Zone modifiée pendant le dépôt ; recommencer le geste".into());
                }
                insertion::prepare(
                    &current,
                    &browser.label(&name),
                    reference,
                    (
                        Transform::IDENTITY,
                        PlacementSnap {
                            grid_step_m: None,
                            surface_offset_m: Some(0.0),
                        },
                    ),
                    point,
                )
            });
            on_command.run(result);
        });
    });
    event.prevent_default();
    PENDING.with(|slot| {
        slot.replace(Some(Gesture {
            start: [event.client_x(), event.client_y()],
            moved: false,
            callback,
        }))
    });
    super::placements::report(
        "Déposer sur le terrain : échelle 1, rotation 0, pivot sur la surface. Un aperçu, puis Appliquer ; Échap annule.",
    );
}

pub(crate) fn motion(event: &web_sys::MouseEvent) {
    PENDING.with(|slot| {
        if let Some(gesture) = slot.borrow_mut().as_mut() {
            gesture.moved |= event.client_x().abs_diff(gesture.start[0]) >= 6
                || event.client_y().abs_diff(gesture.start[1]) >= 6;
        }
    });
}

#[allow(
    clippy::cast_precision_loss,
    reason = "Browser pixel coordinates fit f32 precision"
)]
pub(crate) fn receive(event: &web_sys::MouseEvent) {
    if event.button() != 0 {
        return;
    }
    motion(event);
    let pending = PENDING.with(RefCell::take);
    let Some(gesture) = pending else {
        return;
    };
    if !gesture.moved {
        return;
    }
    SUPPRESS_CLICK.with(|slot| slot.set(true));
    event.prevent_default();
    let callback = gesture.callback;
    if !crate::authoring_viewport::can_preview_asset() {
        callback.run(Err(
            "Revenir à une zone en mode édition avant de déposer".into()
        ));
        return;
    }
    let Some(canvas) = event
        .target()
        .and_then(|target| target.dyn_into::<web_sys::HtmlElement>().ok())
        .filter(|target| target.id() == "forge-authoring-canvas")
    else {
        callback.run(Err(
            "Dépôt refusé : cible différente du canvas terrain".into()
        ));
        return;
    };
    let (width, height) = (canvas.client_width(), canvas.client_height());
    if width <= 0 || height <= 0 {
        callback.run(Err("Dépôt refusé : vue de terrain sans dimensions".into()));
        return;
    }
    let position = bevy::prelude::Vec2::new(
        event.offset_x() as f32 / width as f32,
        event.offset_y() as f32 / height as f32,
    );
    super::placements::report("Dépôt reçu : recherche du point sur le terrain…");
    crate::authoring_brush_pointer::pick_at(position, callback);
}
